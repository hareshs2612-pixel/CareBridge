/**
 * Translate helper: returns translated string if present in active language,
 * else safely falls back to English, preserving diagnostic safety.
 */
export function t(key: string, lang?: AppLanguage): string {
  const activeLang = lang || dataStore.getAppLanguage() || 'en';
  const dict = TRANSLATIONS[activeLang];
  if (dict && dict[key] && dict[key].trim() !== '') {
    return dict[key];
  }
  // Safe English fallback
  const fallbackDict = TRANSLATIONS['en'];
  if (fallbackDict && fallbackDict[key]) {
    return fallbackDict[key];
  }
  return key;
}

/**
 * Reactive React hook for i18n
 */
export function useTranslation() {
  const [lang, setLang] = useState<AppLanguage>(dataStore.getAppLanguage());

  useEffect(() => {
    return dataStore.subscribe(() => {
      setLang(dataStore.getAppLanguage());
    });
  }, []);

  const translate = (key: string) => t(key, lang);
  const currentOption = SUPPORTED_LANGUAGES.find(l => l.code === lang) || SUPPORTED_LANGUAGES[0];

  return {
    t: translate,
    language: lang,
    setLanguage: (newLang: AppLanguage) => dataStore.setAppLanguage(newLang),
    isFallbackActive: lang !== 'en',
    currentOption,
    supportedLanguages: SUPPORTED_LANGUAGES
  };
}
